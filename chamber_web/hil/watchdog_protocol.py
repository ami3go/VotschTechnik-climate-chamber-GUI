"""Wire protocol between the application and the H02-C watchdog process.

Pure stdlib: imported inside the spawned watchdog child as well as the app.
Messages are dictionaries sent over an authenticated ``multiprocessing``
connection (HMAC handshake with a per-launch secret generated by the app).
The watchdog never receives device-command authority; the only action it can
request is the approved G04 STOP path handled by the application.
"""
from __future__ import annotations

PROTOCOL_VERSION = 1

READY = "READY"
ACK = "ACK"
CONFIG = "CONFIG"
HEARTBEAT = "HEARTBEAT"
STOP_REQUEST = "STOP_REQUEST"
SHUTDOWN = "SHUTDOWN"

STATE_IDLE = "IDLE"
STATE_ARMED = "ARMED"

# Child exit codes (never a PASS):
EXIT_CONNECT_FAILED = 2
EXIT_PARENT_LOST = 3
EXIT_CONFIG_INVALID = 4
EXIT_PROTOCOL_ERROR = 5


class WatchdogProtocolError(Exception):
    """A protocol/configuration violation detected by either side."""


def validate_limits(limits: object) -> None:
    """Child-side bounded validation mirroring H02WatchdogLimits v1."""
    names = {
        "schema_version", "controller_command_timeout_s", "readback_deadline_s",
        "max_telemetry_gap_s", "profile_step_deadline_s", "whole_profile_deadline_s",
        "recorder_heartbeat_s", "process_heartbeat_s", "supervisor_heartbeat_s",
        "cleanup_timeout_s", "stop_verification_timeout_s",
    }
    if not isinstance(limits, dict) or set(limits) != names:
        raise WatchdogProtocolError("Watchdog limits must match v1 schema")
    if limits["schema_version"] != 1:
        raise WatchdogProtocolError("Unrecognized watchdog schema")
    for name in names - {"schema_version"}:
        value = limits[name]
        if isinstance(value, bool) or not isinstance(value, (int, float)):
            raise WatchdogProtocolError("Invalid watchdog limit: " + name)
        if not 0 < value <= 1_209_600:
            raise WatchdogProtocolError("Invalid watchdog limit: " + name)
    if limits["max_telemetry_gap_s"] > 5 or limits["readback_deadline_s"] > 5:
        raise WatchdogProtocolError("Telemetry/readback freshness limit exceeded")
    if limits["profile_step_deadline_s"] > limits["whole_profile_deadline_s"]:
        raise WatchdogProtocolError("Step deadline exceeds whole-run deadline")
